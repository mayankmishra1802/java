public class Loops {

    public static void main(String[] args) {
        // for loop
        for(int i=0;i<5;i++){
            System.out.println("for"); 
        }

        // while loop
        int i=0;
        while(i<5){
            System.out.println("while");
            i++;
        }

        // do-while loop
        int j=0;    
        do{
            System.out.println("do-while");
            j++;
        }
        while(j<5);
    }
    
}
